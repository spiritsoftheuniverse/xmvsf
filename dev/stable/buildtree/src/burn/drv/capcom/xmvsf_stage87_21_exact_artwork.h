template <size_t N> inline bool Contains(const unsigned (&xs)[N],unsigned tile) {
    return std::binary_search(xs,xs+N,tile);
}
inline Decision Classify(const XM8717::Source& s,unsigned frame,
                         unsigned priority,unsigned palette,unsigned tile,bool gameplay){
  if(!Enabled() || !gameplay || priority!=6u)return Keep;
  const bool recent=XM8717::Recent(s,frame);
  // Repeated identical sprite groups from these three secondary writer structures
  // represent an afterimage even on its FIRST frame, before live body-tile learning.
  if(recent && s.owner==0u && (palette==21u || palette==22u) &&
    (s.a0==0xFF9C00u || s.a0==0xFF9CC0u || s.a0==0xFF9D80u) &&
    Contains(kEchoTiles,tile))return GrayEcho;
  // Verified distinct effect artwork under palette 6/7, not actor body artwork.
  // Don't override directly fighter-owned sprites, preserving the source mask.
  if((palette==6u || palette==7u) && (!recent || s.owner==0u) &&
     Contains(kFxTiles,tile))return FullRGB;
  return Keep;
}
