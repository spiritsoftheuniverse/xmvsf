static inline const unsigned char* xm251Glyph(char ch) {
    if (ch >= 'a' && ch <= 'z') ch = char(ch - 'a' + 'A');
    for (unsigned i=0;i<sizeof(xm251Font)/sizeof(xm251Font[0]);++i)
        if(xm251Font[i].c==ch) return xm251Font[i].rows;
    return nullptr;  // Spaces are deliberately blank.
}
static inline void xm25SmallText(SDL_Renderer* r,const char* text,int x,int y,int width){
    if(!r || !text || width<6)return;
    SDL_SetRenderDrawColor(r,210,225,255,255);
    const int limit=width/6;
    for(int i=0;text[i] && i<limit;++i){
        const unsigned char* rows=xm251Glyph(text[i]);
        if(!rows)continue;
        for(int yy=0;yy<7;++yy)for(int xx=0;xx<5;++xx){
            if(rows[yy] & (1u<<(4-xx))){SDL_Rect pixel={x+i*6+xx,y+yy,1,1};SDL_RenderFillRect(r,&pixel);}
        }
    }
}
